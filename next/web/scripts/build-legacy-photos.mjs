// Builds the photos pages' stylesheets from the legacy site, so the native React photos pages
// (src/components/photos) use the original CSS and look identical. Re-run after changing the CSS of
// a legacy photos page:
//
//   node scripts/build-legacy-photos.mjs
//
//   legacy photos/index.html <style>          -> src/app/photos/legacy-home.css   (scoped to .lp-home)
//   legacy /style.css + photos/album <style>s  -> src/app/photos/legacy-album.css  (scoped to .lp-album)
//
// Both pages live in one app, so their rules would collide (each defines .photos-header,
// .toilet-toast ...). Every selector is prefixed with the page's wrapper class; `body`, `:root` and
// `*` rules apply to the wrapper. State classes the legacy pages put on <html> (all-mode, sel-mode,
// has-tabbar ...) are matched on the wrapper, which the React page toggles; `has-token` also still
// matches on <html>, where a blocking script sets it before first paint. Page scrollbar and
// view-transition rules are left to globals.css and /nav-motion.js.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.resolve(WEB, "..");
const read = (file) => fs.readFileSync(path.join(ROOT, file), "utf8");

// ---------- CSS ----------

const styleBlocks = (html) => [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");

function scopeSelector(sel, prefix) {
  sel = sel.trim();
  if (/^::?-webkit-scrollbar|^::view-transition/.test(sel)) return null;
  if (sel.startsWith(":root")) return prefix + sel.slice(5);
  const html = sel.match(/^html((?:[.#[:][^\s>+~]*)*)(.*)$/);
  if (html) {
    const rest = html[2].trim();
    const cls = html[1];
    const tail = /^body\b/.test(rest) ? rest.slice(4) : rest ? ` ${rest}` : "";
    if (!cls) return tail ? `${prefix}${tail}` : null;
    return `${prefix}${cls}${tail}, html${cls} ${prefix}${tail}`;
  }
  if (/^body\b/.test(sel)) return prefix + sel.slice(4);
  if (sel === "*" || sel.startsWith("*")) return `${prefix} ${sel}`;
  return `${prefix} ${sel}`;
}

function scopeCss(css, prefix, from) {
  const root = postcss.parse(css, { from });
  root.walkAtRules((at) => {
    if (at.name === "view-transition") at.remove();
  });
  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
    const scoped = rule.selectors.map((s) => scopeSelector(s, prefix)).filter(Boolean);
    if (!scoped.length) rule.remove();
    else rule.selectors = [...new Set(scoped)];
  });
  return root.toString();
}

// ---------- Pages ----------

const PAGES = [
  { name: "home", file: "photos/index.html", bodyClass: "lp-home", css: ["photos/index.html"] },
  { name: "album", file: "photos/album/index.html", bodyClass: "lp-album", css: ["style.css", "photos/album/index.html"] },
];

for (const page of PAGES) {
  const css = page.css.map((src) => scopeCss(src.endsWith(".css") ? read(src) : styleBlocks(read(src)), `.${page.bodyClass}`, src)).join("\n");
  const out = `src/app/photos/legacy-${page.name}.css`;
  fs.writeFileSync(path.join(WEB, out), `/* GENERATED by scripts/build-legacy-photos.mjs from ${page.css.join(" + ")} — do not edit; edit the legacy page and re-run. */\n${css}`);
  console.log(`${out}: ${(css.length / 1024).toFixed(1)} KB`);
}
